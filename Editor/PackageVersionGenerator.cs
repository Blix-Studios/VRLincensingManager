using System.IO;
using UnityEditor;
using UnityEngine;

namespace VRLicensing.Editor
{
    /// <summary>
    /// Keeps <c>Runtime/Scripts/PackageVersion.cs</c> equal to "version" in package.json, so the
    /// constant sent as <c>p_upm_version</c> is never typed by hand (v1.12.0-pre.16, spec 11 §6).
    /// Runs when the editor loads and only where the package is editable (local or embedded);
    /// in a consumer project the package cache is read-only and already carries the right file.
    /// </summary>
    [InitializeOnLoad]
    public static class PackageVersionGenerator
    {
        private const string RelativePath = "Runtime/Scripts/PackageVersion.cs";

        static PackageVersionGenerator()
        {
            EditorApplication.delayCall += () => Generate();
        }

        /// <summary>Exact content of the generated file for a version.</summary>
        public static string Source(string version)
        {
            return
                "// <auto-generated>\n" +
                "// Generated from package.json by Editor/PackageVersionGenerator.cs. Do not edit: bump \"version\"\n" +
                "// in package.json and let the editor regenerate this file (PackageVersionTests checks they match).\n" +
                "// </auto-generated>\n" +
                "namespace VRLicensing\n" +
                "{\n" +
                "    /// <summary>Version of com.blixstudios.vr-licensing, sent as <c>p_upm_version</c>.</summary>\n" +
                "    public static class PackageVersion\n" +
                "    {\n" +
                "        public const string Value = \"" + version + "\";\n" +
                "    }\n" +
                "}\n";
        }

        /// <summary>Rewrites the file when it is stale. Returns true when it wrote.</summary>
        public static bool Generate()
        {
            var info = UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(PackageVersionGenerator).Assembly);
            if (info == null) return false;
            if (info.source != UnityEditor.PackageManager.PackageSource.Local &&
                info.source != UnityEditor.PackageManager.PackageSource.Embedded) return false;

            string path = Path.Combine(info.resolvedPath, RelativePath);
            string expected = Source(info.version);
            string current = File.Exists(path) ? File.ReadAllText(path).Replace("\r\n", "\n") : null;
            if (current == expected) return false;

            File.WriteAllText(path, expected);
            Debug.Log($"[VR Licensing] PackageVersion.cs regenerated for {info.version}.");
            AssetDatabase.Refresh();
            return true;
        }

        [MenuItem("Tools/Blix Studios/Licensing/Regenerate PackageVersion.cs")]
        private static void GenerateFromMenu()
        {
            if (!Generate()) Debug.Log("[VR Licensing] PackageVersion.cs is already up to date (or the package is read-only here).");
        }
    }
}
